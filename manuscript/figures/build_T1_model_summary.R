wl("% auto-generated by build_T1_model_summary.R -- per-model summary")
wl("\\begin{tabular}{lccccccc}")
wl("\\hline")
wl("Model & Pools & Free & $R^2$ & $R^2$ & RMSE & Eff.\\ flux & $\\sigma_{\\mathrm{init}}$ \\\\")
wl(" & & params & (cal) & (hold) & (hold) & $\\sigma_{\\mathrm{inp}}\\bar J$ & \\\\")
wl("\\hline")
for (i in seq_len(nrow(T))) with(T[i, ],
  wl(sprintf("%s & %d & %d & %.3f & %.3f & %.0f & %.1f & %.2f \\\\",
             model, pools, free, R2c, R2h, RMSE, effJ, sinit)))
wl("\\hline")
wl("\\end{tabular}")
close(con)
cat("\nwrote", f, "\n")
cat("(Eff. flux = median sigma_input x Jbar=2.472 tC/ha/yr; all within the physical [0.5,8.7] envelope.)\n")
cat("2084 forecast (tC/ha):", paste(sprintf("%s %.0f", T$model, T$soc2084), collapse="  "), "\n")
